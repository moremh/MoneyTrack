export const normalizeUiLanguage = (value) => {
  const language =
    String(value || "")
      .toLowerCase()
      .split("-")[0];

  return ["es", "en", "it"].includes(language)
    ? language
    : "es";
};

export const getStoredUiLanguage = () => {
  if (typeof window === "undefined") {
    return "es";
  }

  return normalizeUiLanguage(
    window.localStorage.getItem(
      "moneytrack-ui-language"
    ) ||
      window.navigator?.language ||
      "es"
  );
};

const genericSystemTranslation = (
  source,
  language
) => {
  if (
    !SYSTEM_PREFIXES.some(
      (prefix) =>
        source.startsWith(prefix)
    )
  ) {
    return null;
  }

  const isError =
    source.startsWith("No se pudo") ||
    source.startsWith("No se pudieron") ||
    source.startsWith("No se encontró") ||
    source.startsWith("No se encontraron");

  const isInstruction =
    source.startsWith("Debés ") ||
    source.startsWith("Debes ") ||
    source.startsWith("Tenés ") ||
    source.startsWith("Seleccioná ");

  if (language === "it") {
    if (isError) {
      return "Impossibile completare l'operazione. Controlla i dati e riprova.";
    }

    if (isInstruction) {
      return "Controlla i dati richiesti prima di continuare.";
    }

    return "Controlla queste informazioni prima di continuare.";
  }

  if (isError) {
    return "The operation could not be completed. Check the information and try again.";
  }

  if (isInstruction) {
    return "Check the required information before continuing.";
  }

  return "Check this information before continuing.";
};

export const translateInterfaceText = (
  value,
  language = "es"
) => {
  const source = normalize(value);
  const target = normalizeUiLanguage(language);

  if (!source || target === "es") {
    return source;
  }

  const exact =
    V5_TRANSLATIONS[source]?.[target] ||
    EXACT_TRANSLATIONS[source]?.[target];

  if (exact) {
    return exact;
  }

  for (const item of DYNAMIC_TRANSLATIONS) {
    if (item.pattern.test(source)) {
      return source.replace(
        item.pattern,
        item[target]
      );
    }
  }

  return source;
};

export const hasInterfaceTranslation = (
  value
) => {
  const source = normalize(value);

  return Boolean(
    V5_TRANSLATIONS[source] ||
    EXACT_TRANSLATIONS[source] ||
    DYNAMIC_TRANSLATIONS.some(
      (item) =>
        item.pattern.test(source)
    ) ||
    SYSTEM_PREFIXES.some(
      (prefix) =>
        source.startsWith(prefix)
    )
  );
};

export const translateStoredText = (
  value
) =>
  translateInterfaceText(
    value,
    getStoredUiLanguage()
  );
