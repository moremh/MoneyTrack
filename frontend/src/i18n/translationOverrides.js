const normalize = (value) =>
  String(value || "")
    .replace(/\s+/g, " ")
    .trim();

const PATTERNS = [
  {
    pattern:
      /^(\d+(?:[.,]\d+)?)% completado$/,
    en:
      "$1% completed",
    it:
      "$1% completato",
  },
  {
    pattern:
      /^Durante este mes calendario registraste (\d+) movimientos\.$/,
    en:
      "You recorded $1 movements during this calendar month.",
    it:
      "Hai registrato $1 movimenti durante questo mese di calendario.",
  },
  {
    pattern:
      /^Movimientos del período:\s*(\d+)$/,
    en:
      "Movements in period: $1",
    it:
      "Movimenti del periodo: $1",
  },
  {
    pattern:
      /^Movimientos totales registrados:\s*(\d+)$/,
    en:
      "Total recorded movements: $1",
    it:
      "Movimenti totali registrati: $1",
  },
];

export const translateOverride =
  (
    value,
    language
  ) => {
    const source =
      normalize(value);

    const exact =
      OVERRIDES[source]?.[
        language
      ];

    if (exact) {
      return exact;
    }

    for (
      const item of
      PATTERNS
    ) {
      if (
        item.pattern.test(
          source
        )
      ) {
        return source.replace(
          item.pattern,
          item[language]
        );
      }
    }

    return null;
  };
